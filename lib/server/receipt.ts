import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { query } from './db';
import { sha256 } from './auth';
import { chargeName, calc, nu } from '../calc';

const FOREST = rgb(0.086, 0.2, 0);
const LIME = rgb(0.62, 0.91, 0.44);
const MUTED = rgb(0.36, 0.44, 0.48);

/** Build the customer's payment receipt as a PDF, with a seal and a verification code. */
export async function buildReceiptPdf(r: {
  number: string;
  paidAt: Date;
  merchant: { name: string; addr?: string; phone?: string; email?: string };
  customer: { name?: string; email?: string };
  invoiceNo: string;
  amountMinor: number;
  txnId: string;
  providerTxnId: string;
  orderNo: string;
  provider: string;
  code: string;
  lines: string[];
}) {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const text = (
    t: string,
    x: number,
    y: number,
    size = 11,
    f = font,
    color = rgb(0.05, 0.06, 0.05),
  ) => page.drawText(t, { x, y, size, font: f, color });

  // header band with logo mark
  page.drawRectangle({ x: 0, y: 760, width: 595, height: 82, color: FOREST });
  page.drawRectangle({ x: 40, y: 780, width: 40, height: 40, color: LIME });
  text('G', 53, 790, 24, bold, FOREST);
  text('GlobalPay.bt', 92, 797, 20, bold, rgb(1, 1, 1));
  text('PAYMENT RECEIPT', 400, 797, 16, bold, LIME);

  text(`Receipt no. ${r.number}`, 40, 730, 12, bold);
  text(
    `Date paid: ${r.paidAt.toISOString().replace('T', ' ').slice(0, 16)} UTC`,
    40,
    713,
    10,
    font,
    MUTED,
  );
  text('PAID', 480, 722, 26, bold, FOREST);

  let y = 676;
  const row = (k: string, v: string) => {
    text(k, 40, y, 10, font, MUTED);
    text(v, 190, y, 11, bold);
    y -= 22;
  };
  const section = (title: string) => {
    y -= 14;
    text(title, 40, y, 9, bold, MUTED);
    y -= 22;
  };
  y += 14;
  section('PAID TO');
  row('Merchant', r.merchant.name);
  if (r.merchant.addr) row('Address', r.merchant.addr);
  section('PAID BY');
  row('Customer', r.customer.name || '—');
  row('Email', r.customer.email || '—');
  section('PAYMENT DETAILS');
  row('Invoice', r.invoiceNo);
  row('Amount paid', nu(r.amountMinor));
  row('Payment method', `Bank account debit via ${r.provider} BFS Secure`);
  row('BFS transaction ID', r.providerTxnId);
  row('Order number', r.orderNo);
  row('Response', `${r.code} (Approved)`);
  row('GlobalPay reference', r.txnId);
  section('ITEMS');
  for (const l of r.lines.slice(0, 8)) {
    text(l.slice(0, 95), 40, y, 10);
    y -= 16;
  }

  // seal
  page.drawCircle({ x: 480, y: 215, size: 62, borderColor: FOREST, borderWidth: 3 });
  page.drawCircle({ x: 480, y: 215, size: 54, borderColor: LIME, borderWidth: 1.5 });
  const c = (t: string, yy: number, s: number, f = bold) =>
    text(t, 480 - f.widthOfTextAtSize(t, s) / 2, yy, s, f, FOREST);
  c('GlobalPay.bt', 232, 12);
  c('VERIFIED PAYMENT', 214, 8);
  c(r.paidAt.toISOString().slice(0, 10), 198, 9, font);

  const code = sha256(`${r.number}|${r.txnId}|${r.providerTxnId}|${r.amountMinor}`)
    .slice(0, 16)
    .toUpperCase();
  text(`Verification code: ${code}`, 40, 120, 10, bold);
  text(
    'This receipt was generated by GlobalPay.bt after the payment provider confirmed the payment.',
    40,
    96,
    8.5,
    font,
    MUTED,
  );
  text(
    'GlobalPay.bt does not hold funds. The payment was settled by your bank directly to the merchant.',
    40,
    84,
    8.5,
    font,
    MUTED,
  );
  text(
    'A copy of this receipt is kept in the GlobalPay.bt system. Computer generated; valid without signature.',
    40,
    72,
    8.5,
    font,
    MUTED,
  );
  return Buffer.from(await pdf.save());
}

/** Return the stored receipt PDF for a successful transaction, creating it the first time. */
export async function ensureReceipt(
  txnId: string,
): Promise<{ pdf: Buffer; number: string } | null> {
  const [have] = await query('SELECT number, pdf FROM receipts WHERE txn_id = $1', [txnId]);
  if (have) return { pdf: have.pdf, number: have.number };
  const [t] = await query(
    `SELECT t.*, m.legal_name, m.address, m.phone, m.email AS m_email, i.invoice_no, i.id AS inv_id
       FROM transactions t JOIN merchants m ON m.id = t.merchant_id LEFT JOIN invoices i ON i.id = t.invoice_id
      WHERE t.id = $1 AND t.status = 'Successful'`,
    [txnId],
  );
  if (!t) return null;
  let lines: string[] = [];
  if (t.inv_id) {
    const items = await query(
      'SELECT * FROM invoice_items WHERE invoice_id = $1 ORDER BY line_no',
      [t.inv_id],
    );
    const chs = await query(
      'SELECT * FROM invoice_charges WHERE invoice_id = $1 ORDER BY line_no',
      [t.inv_id],
    );
    const c = calc(
      items.map((i: any) => ({
        d: i.description,
        q: Number(i.quantity),
        p: i.unit_price_minor / 100,
        disc: { kind: i.discount_kind, v: Number(i.discount_value) },
      })),
      chs.map((x: any) => ({ kind: x.kind, label: x.label, mode: x.mode, v: Number(x.value) })),
    );
    lines = [
      ...items.map(
        (i: any, n: number) =>
          `${i.description}  x ${Number(i.quantity)}  = ${nu(c.lines[n].net)}${c.lines[n].disc ? ' (after discount)' : ''}`,
      ),
      ...c.charges.map((x) => `${chargeName(x)}: ${nu(x.amount)}`),
    ];
  } else lines = [t.kind === 'subscription' ? 'GlobalPay.bt subscription fee' : 'Payment'];
  const [{ n }] = await query("SELECT nextval('receipt_seq') AS n");
  const number = `GPR-${new Date(t.occurred_at).getUTCFullYear()}-${String(n).padStart(6, '0')}`;
  const pdf = await buildReceiptPdf({
    number,
    paidAt: new Date(t.occurred_at),
    merchant: { name: t.legal_name, addr: t.address },
    customer: { name: t.customer_name, email: t.customer_email },
    invoiceNo: t.invoice_no || (t.kind === 'subscription' ? 'Subscription' : '—'),
    amountMinor: t.amount_minor,
    txnId: t.id,
    providerTxnId: t.provider_txn_id || '—',
    orderNo: t.order_no || '—',
    provider: t.provider,
    code: t.response_code || '00',
    lines,
  });
  await query(
    'INSERT INTO receipts (txn_id, number, pdf) VALUES ($1,$2,$3) ON CONFLICT DO NOTHING',
    [txnId, number, pdf],
  );
  return { pdf, number };
}
